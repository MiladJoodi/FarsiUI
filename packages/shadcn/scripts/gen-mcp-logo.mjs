import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const root = path.dirname(fileURLToPath(import.meta.url))
const assets = path.join(root, "../src/mcp/assets")
const outPath = path.join(root, "../src/mcp/logo.ts")

function dataUri(fileName) {
  const buf = fs.readFileSync(path.join(assets, fileName))
  return `data:image/png;base64,${buf.toString("base64")}`
}

const icons = [
  {
    src: dataUri("logo-192.png"),
    mimeType: "image/png",
    sizes: ["192x192"],
  },
  {
    src: dataUri("logo-48.png"),
    mimeType: "image/png",
    sizes: ["48x48"],
  },
  // HTTPS fallbacks for clients that prefer remote icons over data URIs.
  {
    src: "https://farsiui.ir/farsiui/favicon.png",
    mimeType: "image/png",
    sizes: ["any"],
  },
  {
    src: "https://farsiui.ir/farsiui/logo.png",
    mimeType: "image/png",
    sizes: ["any"],
  },
]

const body = [
  "/** Auto-generated by scripts/gen-mcp-logo.mjs — do not edit by hand. */",
  "export const FARSIUI_MCP_ICONS: Array<{",
  "  src: string",
  "  mimeType: string",
  "  sizes: string[]",
  "}> = " + JSON.stringify(icons, null, 2),
  "",
  "/** @deprecated Prefer FARSIUI_MCP_ICONS */",
  "export const FARSIUI_MCP_ICON = FARSIUI_MCP_ICONS[0]",
  "",
]

fs.writeFileSync(outPath, body.join("\n"))
console.log(`wrote ${outPath} (${icons.length} icons)`)
