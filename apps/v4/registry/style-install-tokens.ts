/**
 * Installable semantic tokens for Design Systems that ship as real registry
 * styles (glass / rose / nili / khesht). Values mirror *-tokens.css so CLI
 * init writes the same palette + role surfaces to consumer :root / .dark.
 */

export type StyleInstallTokens = {
  light: Record<string, string>
  dark: Record<string, string>
}

/** Role / elevation tokens referenced by baked style CSS (`var(--surface)`, …). */
function roleTokens(tokens: {
  radiusField: string
  radiusSurface: string
  radiusOverlay: string
  radiusControl: string
  surface: string
  surfaceMuted: string
  surfaceBorder: string
  surfaceForeground: string
  field: string
  fieldBorder: string
  fieldShadow: string
  control: string
  controlBorder: string
  controlShadow: string
  overlay: string
  overlayShadow: string
  shadowSurface: string
  shadowField: string
  shadowOverlay: string
  shadowControl: string
  shadowPress: string
  extra?: Record<string, string>
}): Record<string, string> {
  return {
    "radius-field": tokens.radiusField,
    "radius-surface": tokens.radiusSurface,
    "radius-overlay": tokens.radiusOverlay,
    "radius-control": tokens.radiusControl,
    surface: tokens.surface,
    "surface-muted": tokens.surfaceMuted,
    "surface-border": tokens.surfaceBorder,
    "surface-foreground": tokens.surfaceForeground,
    field: tokens.field,
    "field-border": tokens.fieldBorder,
    "field-shadow": tokens.fieldShadow,
    control: tokens.control,
    "control-border": tokens.controlBorder,
    "control-shadow": tokens.controlShadow,
    overlay: tokens.overlay,
    "overlay-shadow": tokens.overlayShadow,
    "shadow-surface": tokens.shadowSurface,
    "shadow-field": tokens.shadowField,
    "shadow-overlay": tokens.shadowOverlay,
    "shadow-control": tokens.shadowControl,
    "shadow-press": tokens.shadowPress,
    ...tokens.extra,
  }
}

